#[test]
fn release_checks_container_label_and_extracted_cli_identity() {
    let fixture = valid_fixture("release-container-success", "1.2.3");
    fixture.write(
        "fake-runtime",
        r#"#!/usr/bin/env sh
set -eu
case "$1" in
  inspect)
    printf '%s\n' "${FAKE_AGENTD_REF:?}"
    ;;
  create)
    printf 'fake-container\n'
    ;;
  cp)
    destination="$3"
    cat >"$destination" <<'EOF'
#!/usr/bin/env sh
printf 'agentd 1.2.3\n'
EOF
    chmod +x "$destination"
    ;;
  rm)
    exit 0
    ;;
  *)
    echo "unexpected fake-runtime command: $*" >&2
    exit 64
    ;;
esac
"#,
    );
    fs::set_permissions(
        fixture.root.join("fake-runtime"),
        fs::Permissions::from_mode(0o755),
    )
    .expect("fake runtime should be executable");

    let output = Command::new("bash")
        .arg(fixture.root.join("scripts/release-check"))
        .args([
            "release",
            "v1.2.3",
            "--container-image",
            "localhost/agentd:v1.2.3",
        ])
        .current_dir(&fixture.root)
        .env(
            "AGENTD_CONTAINER_RUNTIME",
            fixture.root.join("fake-runtime"),
        )
        .env("FAKE_AGENTD_REF", "v1.2.3")
        .output()
        .expect("release-check should run");

    assert_success(&output);
}

