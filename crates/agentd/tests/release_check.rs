use std::fs;
use std::os::unix::fs::PermissionsExt;
use std::path::{Path, PathBuf};
use std::process::{Command, Output};

fn workspace_root() -> PathBuf {
    Path::new(env!("CARGO_MANIFEST_DIR"))
        .ancestors()
        .nth(2)
        .expect("workspace root")
        .to_path_buf()
}

struct Fixture {
    root: PathBuf,
}

impl Fixture {
    fn new(name: &str) -> Self {
        let root = std::env::temp_dir().join(format!(
            "agentd-release-check-{name}-{}-{}",
            std::process::id(),
            std::time::SystemTime::now()
                .duration_since(std::time::UNIX_EPOCH)
                .expect("system time should be after unix epoch")
                .as_nanos()
        ));
        fs::create_dir_all(&root).expect("fixture root should be created");
        Self { root }
    }

    fn write(&self, relative: &str, contents: &str) {
        let path = self.root.join(relative);
        if let Some(parent) = path.parent() {
            fs::create_dir_all(parent).expect("fixture parent should be created");
        }
        fs::write(path, contents).expect("fixture file should be written");
    }

    fn install_release_check(&self) -> PathBuf {
        let source = workspace_root().join("scripts/release-check");
        let destination = self.root.join("scripts/release-check");
        fs::create_dir_all(destination.parent().expect("script parent"))
            .expect("script parent should be created");
        fs::copy(source, &destination).expect("release-check script should exist");
        fs::set_permissions(&destination, fs::Permissions::from_mode(0o755))
            .expect("release-check script should be executable");
        destination
    }

    fn run_release_check(&self, args: &[&str]) -> Output {
        Command::new("bash")
            .arg(self.root.join("scripts/release-check"))
            .args(args)
            .current_dir(&self.root)
            .output()
            .expect("release-check should run")
    }
}

impl Drop for Fixture {
    fn drop(&mut self) {
        let _ = fs::remove_dir_all(&self.root);
    }
}

fn valid_fixture(name: &str, version: &str) -> Fixture {
    let fixture = Fixture::new(name);
    fixture.write(
        "Cargo.toml",
        &format!(
            r#"[workspace]
members = [
    "crates/agentd",
    "crates/agentd-runner",
    "crates/agentd-scheduler",
]

[workspace.package]
version = "{version}"
"#
        ),
    );
    fixture.write(
        "Cargo.lock",
        &format!(
            r#"# This file is automatically @generated by Cargo.
version = 4

[[package]]
name = "agentd"
version = "{version}"

[[package]]
name = "agentd-runner"
version = "{version}"

[[package]]
name = "agentd-scheduler"
version = "{version}"
"#
        ),
    );
    for crate_name in ["agentd", "agentd-runner", "agentd-scheduler"] {
        fixture.write(
            &format!("crates/{crate_name}/Cargo.toml"),
            &format!(
                r#"[package]
name = "{crate_name}"
version.workspace = true
"#
            ),
        );
        fixture.write(&format!("crates/{crate_name}/src/lib.rs"), "");
    }
    fixture.write(
        "CHANGELOG.md",
        &format!(
            r#"# Changelog

## [Unreleased]

## [{version}] — 2026-05-07

### Added

- Release ceremony tooling.
"#
        ),
    );
    fixture.write(
        "Containerfile",
        r#"ARG AGENTD_REF=local
LABEL org.tesserine.agentd.ref="${AGENTD_REF}"
COPY --from=builder /workspace/target/release/agentd /usr/local/bin/agentd
"#,
    );
    fixture.write(
        ".github/workflows/release.yml",
        r#"name: Release

on:
  push:
    tags:
      - "v*"

jobs:
  publish:
    steps:
      - name: Checkout
        uses: actions/checkout@v4

      - name: Validate release tag
        run: ./scripts/release-check release "$GITHUB_REF_NAME"

      - name: Install container tooling
        run: sudo apt-get install -y podman
"#,
    );
    fixture.install_release_check();
    fixture
}

fn workspace_manifest_with_members(version: &str, members: &[&str]) -> String {
    let members = members
        .iter()
        .map(|member| format!("    \"{member}\","))
        .collect::<Vec<_>>()
        .join("\n");

    format!(
        r#"[workspace]
members = [
{members}
]

[workspace.package]
version = "{version}"
"#
    )
}

fn cargo_lock_with_packages(packages: &[(&str, &str)]) -> String {
    let packages = packages
        .iter()
        .map(|(name, package_version)| {
            format!(
                r#"[[package]]
name = "{name}"
version = "{package_version}"
"#
            )
        })
        .collect::<Vec<_>>()
        .join("\n");

    format!(
        r#"# This file is automatically @generated by Cargo.
version = 4

{packages}
"#
    )
}

fn assert_success(output: &Output) {
    assert!(
        output.status.success(),
        "command failed\nstdout:\n{}\nstderr:\n{}",
        String::from_utf8_lossy(&output.stdout),
        String::from_utf8_lossy(&output.stderr)
    );
}

fn assert_failure_contains(output: &Output, expected: &str) {
    assert!(
        !output.status.success(),
        "command unexpectedly succeeded\nstdout:\n{}\nstderr:\n{}",
        String::from_utf8_lossy(&output.stdout),
        String::from_utf8_lossy(&output.stderr)
    );
    let stderr = String::from_utf8_lossy(&output.stderr);
    assert!(
        stderr.contains(expected),
        "stderr did not contain {expected:?}\nstderr:\n{stderr}"
    );
}

